#!/usr/bin/env python3
"""Build a self-contained static version of the experiment dashboard.

The bundle mirrors the HTTP contract of ``scripts/dashboard.py`` exactly, so
the same ``dashboard_static/`` frontend runs against either backend:

    api/splits.json
    api/episodes/<split>.json              (full list, no paging)
    api/episode/<split>/<episode_id>.json
    api/preds.json
    api/pred/<name>/<split>/<episode_id>.json
    api/metrics.json
    files/<split>/<episode_id>/<name.png>

Only the RGB/seg PNGs of the first ``--episodes-per-split`` episodes of each
split are copied (``--episodes-per-split 0`` embeds no images at all); the
episode JSONs stay complete apart from frames whose images were not copied.
Depth ``.npz`` files are never copied.

Usage
-----
::

    python3 scripts/dashboard_export.py --data /path/to/wm/data --out site

    python3 scripts/dashboard_export.py --data /path/to/wm/data --out site \
        --pred zeroshot=runs/zs/pred.jsonl --pred sft=runs/sft/pred.jsonl \
        --runs runs/exp001 --episodes-per-split 30

    python3 scripts/dashboard_export.py --data /path/to/wm/data --out site \
        --splits val_id val_ood_forces --episodes-per-split 10

Publish ``SITE_DIR`` with GitHub Pages (see the generated README.md) or upload
it to a Hugging Face dataset repo and point another deployment at it with
``index.html?base=<url-prefix>``.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

# Import the server module for its scanning/prediction/metrics logic.  It is
# stdlib-only and has no import-time side effects (main() is guarded).
sys.path.insert(0, str(Path(__file__).resolve().parent))
import dashboard as dash  # noqa: E402

STATIC_SRC = Path(__file__).resolve().parent / "dashboard_static"

CONFIG_TEMPLATE = """/* Generated by scripts/dashboard_export.py -- static bundle. */
window.DASH_CONFIG = {config};
"""


class Counts:
    def __init__(self) -> None:
        self.json = 0
        self.images = 0
        self.bytes = 0

    def add_json(self, size: int) -> None:
        self.json += 1
        self.bytes += size


def write_json(path: Path, obj, counts: Counts) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = (json.dumps(obj, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    path.write_bytes(body)
    counts.add_json(len(body))


def prepare_out(out: Path) -> Path:
    """Create/refresh the output dir, refusing to wipe unrelated directories."""
    out = out.resolve()
    if out.exists():
        if not out.is_dir():
            raise SystemExit(f"--out is not a directory: {out}")
        if any(out.iterdir()):
            # config.js is the marker written by this script.
            if not (out / "config.js").is_file():
                raise SystemExit(
                    f"refusing to overwrite non-empty directory that is not a "
                    f"dashboard bundle: {out} (empty it first)"
                )
            shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)
    return out


def copy_static(out: Path, counts: Counts) -> None:
    for src in sorted(STATIC_SRC.iterdir()):
        if not src.is_file() or src.name == "config.js":
            continue
        shutil.copy2(src, out / src.name)
    index = out / "index.html"
    html = index.read_text(encoding="utf-8")
    if 'src="config.js"' not in html:
        marker = '<script src="app.js"></script>'
        if marker not in html:
            raise SystemExit(f"cannot find {marker} in {index}")
        html = html.replace(
            marker,
            '<script src="config.js"></script>\n  <script src="app.js"></script>',
        )
        index.write_text(html, encoding="utf-8")
    # GitHub Pages: skip Jekyll so every file is served verbatim.
    (out / ".nojekyll").write_text("", encoding="utf-8")
    config = {
        "api_base": "api/",
        "file_template": "files/{split}/{id}/{name}",
        "paginate": False,
    }
    (out / "config.js").write_text(
        CONFIG_TEMPLATE.format(config=json.dumps(config)), encoding="utf-8"
    )


def copy_episode_files(app: dash.Dashboard, split: str, episode_id: str,
                       out: Path, counts: Counts) -> set[str]:
    """Copy rgb/seg PNGs for one episode; return the set of copied names."""
    dash._component(split, "split")
    dash._component(episode_id, "episode id")
    meta = app._meta_for(split, episode_id)
    ep_dir = app.root / split / episode_id
    copied: set[str] = set()
    for frame in app._scan_frames(split, episode_id, meta):
        for view in frame["views"]:
            for key in ("rgb", "seg"):
                name = view.get(key)
                if not name or name in copied:
                    continue
                dash._component(name, "file name")
                src = ep_dir / name
                if not src.is_file():
                    continue
                dst = out / "files" / split / episode_id / name
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dst)
                copied.add(name)
                counts.images += 1
    return copied


def filter_payload(payload: dict, copied: set[str]) -> dict:
    """Drop frame views whose image was not exported (keeps JSON loadable)."""
    payload = dict(payload)
    frames = []
    for frame in payload.get("frames") or []:
        views = []
        for view in frame.get("views") or []:
            rgb = view.get("rgb")
            if not rgb or rgb not in copied:
                continue
            entry = dict(view)
            if entry.get("seg") and entry["seg"] not in copied:
                entry["seg"] = None
            views.append(entry)
        if views:
            frames.append({**frame, "views": views})
    payload["frames"] = frames
    payload["n_frames"] = len(frames)
    thumb = payload.get("thumb")
    payload["thumb"] = thumb if thumb in copied else None
    return payload


def readme(out: Path, root: Path, splits: list[str], n_episodes: int,
           pred_names: list[str], per_split: int) -> str:
    preds = ", ".join(pred_names) if pred_names else "(none)"
    return f"""# Static world-model dashboard

Self-contained static bundle generated by `scripts/dashboard_export.py`
from `{root}`.

* Splits: {", ".join(splits)}
* Episodes listed: {n_episodes}
* Episodes with copied RGB/seg frames: first {per_split} per split
* Prediction sources: {preds}

## Layout

```
index.html  app.js  style.css  config.js  .nojekyll
api/splits.json
api/episodes/<split>.json
api/episode/<split>/<episode_id>.json
api/preds.json
api/pred/<name>/<split>/<episode_id>.json
api/metrics.json
files/<split>/<episode_id>/<rgb|seg>_*.png
```

`config.js` selects static mode (`api/`, `files/{{split}}/{{id}}/{{name}}`);
`app.js` falls back to server mode when it is absent.

## Run locally

```bash
python3 -m http.server 8801 --directory {out}
# open http://127.0.0.1:8801/
```

## Publish with GitHub Pages

### Option A — dedicated `gh-pages` branch

```bash
cd {out}
git init -b gh-pages
git add -A
git commit -m "static world-model dashboard"
git remote add origin git@github.com:USER/REPO.git
git push -f origin gh-pages
```

Then: repository **Settings -> Pages -> Build and deployment -> Source:
Deploy from a branch -> Branch: `gh-pages` / (root)**.
The site appears at `https://USER.github.io/REPO/`.
The bundle uses relative URLs, so the repository subpath works as-is.

### Option B — `docs/` folder of an existing repo

```bash
mkdir -p docs/dashboard
rsync -a --delete {out}/ docs/dashboard/
git add docs/dashboard
git commit -m "static world-model dashboard"
git push
```

Then: **Settings -> Pages -> Branch: `main` / `/docs`**.
The dashboard lives at `https://USER.github.io/REPO/dashboard/`.

## Point the app at a remotely hosted bundle (Hugging Face dataset repo)

Upload this directory to a **public** dataset repo:

```bash
hf auth login
hf repo create world-model-dashboard --repo-type dataset
hf upload USER/world-model-dashboard {out} --repo-type dataset
```

If the files sit at the repo root, the bundle prefix is:

```
https://huggingface.co/datasets/USER/world-model-dashboard/resolve/main
```

Open any copy of the app (for example the GitHub Pages site) with the prefix
in the query string:

```
https://USER.github.io/REPO/?base=https://huggingface.co/datasets/USER/world-model-dashboard/resolve/main
```

`?base=` switches `api_base` to `<prefix>/api/` and `file_template` to
`<prefix>/files/{{split}}/{{id}}/{{name}}`, disables paging, and works with
any CORS-enabled static host (S3, R2, a lab web server, ...). For a permanent
setup, write the same values into `config.js` instead:

```js
window.DASH_CONFIG = {{
  api_base: "https://huggingface.co/datasets/USER/REPO/resolve/main/api/",
  file_template: "https://huggingface.co/datasets/USER/REPO/resolve/main/files/{{split}}/{{id}}/{{name}}",
  paginate: false,
}};
```

Private repos cannot be read anonymously from a browser; keep the bundle repo
public or serve it through an authenticated proxy.
"""


def main() -> None:
    ap = argparse.ArgumentParser(
        description="Export the dashboard as a fully static site."
    )
    ap.add_argument("--data", required=True,
                    help="data root containing <split>/<episode_id>/meta.json")
    ap.add_argument("--out", required=True, help="output site directory")
    ap.add_argument("--pred", action="append", default=[], type=dash._parse_pred,
                    metavar="NAME=PATH.jsonl", help="prediction jsonl, repeatable")
    ap.add_argument("--runs", default=None,
                    help="run dir with results/table.md and/or metrics.csv")
    ap.add_argument("--episodes-per-split", type=int, default=30, metavar="N",
                    help="episodes per split whose rgb/seg frames are copied "
                         "(default 30; 0 = no episode files)")
    ap.add_argument("--splits", nargs="+", default=None, metavar="S",
                    help="only export these splits (default: all)")
    args = ap.parse_args()

    if args.episodes_per_split < 0:
        ap.error("--episodes-per-split must be >= 0")

    pred_files: dict[str, Path] = {}
    for name, path in args.pred:
        if name in pred_files:
            ap.error(f"duplicate prediction name: {name}")
        pred_files[name] = path

    app = dash.Dashboard(
        Path(args.data), pred_files, Path(args.runs) if args.runs else None
    )
    available = [entry["split"] for entry in app.splits()]
    if args.splits:
        unknown = [s for s in args.splits if s not in available]
        if unknown:
            ap.error(f"unknown split(s): {', '.join(unknown)} "
                     f"(available: {', '.join(available) or 'none'})")
        wanted = set(args.splits)
        chosen = [s for s in available if s in wanted]
    else:
        chosen = available
    if not chosen:
        raise SystemExit(f"no splits with episodes under {app.root}")

    out = prepare_out(Path(args.out))
    counts = Counts()
    copy_static(out, counts)

    split_entries = [entry for entry in app.splits() if entry["split"] in chosen]
    write_json(out / "api" / "splits.json", split_entries, counts)

    n_listed = 0
    for split in chosen:
        ids = app._episode_ids(split)
        n_listed += len(ids)
        budget = ids[: args.episodes_per_split] if args.episodes_per_split else []
        copied: dict[str, set[str]] = {}
        for episode_id in budget:
            copied[episode_id] = copy_episode_files(app, split, episode_id,
                                                    out, counts)

        summaries = []
        for episode_id in ids:
            summary = dict(app.episode_summary(split, episode_id))
            if episode_id not in copied:
                summary["thumb"] = None  # image not part of the bundle
            summaries.append(summary)
        write_json(out / "api" / "episodes" / f"{split}.json", summaries, counts)

        for episode_id in ids:
            payload = filter_payload(
                app.episode_payload(split, episode_id),
                copied.get(episode_id, set()),
            )
            write_json(
                out / "api" / "episode" / split / f"{episode_id}.json",
                payload,
                counts,
            )

    write_json(out / "api" / "preds.json", list(app.pred_names), counts)
    n_pred_files = 0
    for name in app.pred_names:
        for split in chosen:
            for episode_id in app._episode_ids(split):
                records = app.preds[name].get(episode_id) or []
                if not records:
                    continue
                write_json(
                    out / "api" / "pred" / name / split / f"{episode_id}.json",
                    records,
                    counts,
                )
                n_pred_files += 1

    write_json(out / "api" / "metrics.json", app.metrics(), counts)

    (out / "README.md").write_text(
        readme(out, app.root, chosen, n_listed, list(app.pred_names),
               args.episodes_per_split),
        encoding="utf-8",
    )

    print(f"static dashboard bundle: {out}")
    print(f"  splits: {', '.join(chosen)}")
    print(f"  episodes listed: {n_listed} "
          f"(frames copied for first {args.episodes_per_split} per split)")
    print(f"  images copied: {counts.images}")
    print(f"  prediction sources: {', '.join(app.pred_names) or '(none)'} "
          f"({n_pred_files} episode files)")
    print(f"  json files: {counts.json}")
    print("  serve with: python3 -m http.server 8801 --directory "
          f"{out}")


if __name__ == "__main__":
    main()